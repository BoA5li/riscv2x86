@pytest.mark.parametrize('mutation',('wrong-address','wrong-input','wrong-backedge','success-backedge','wrong-return','missing-initial','missing-recompute'))
def test_machine_mutations_cannot_pass_loop_proof(mutation):
    entry=golden();code=bytes.fromhex(entry['bytes']);base=entry['base']
    if mutation=='wrong-address':code=code.replace(bytes.fromhex('f0480fb10a'),bytes.fromhex('f0480fb10b'))
    if mutation=='wrong-input':code=code.replace(bytes.fromhex('48234df0'),bytes.fromhex('48234df8'))
    if mutation=='wrong-backedge':code=code.replace(bytes.fromhex('74ea'),bytes.fromhex('74eb'))
    if mutation=='success-backedge':code=code.replace(bytes.fromhex('74ea'),bytes.fromhex('75ea'))
    if mutation=='wrong-return':code=code.replace(bytes.fromhex('4889f0'),bytes.fromhex('4889c8'))
    if mutation=='missing-initial':code=code.replace(bytes.fromhex('488b02'),bytes.fromhex('4889d0'))
    if mutation=='missing-recompute':code=code.replace(bytes.fromhex('4889c1'),bytes.fromhex('4889c9'))
    with pytest.raises(ValueError):prove(code,base)


def test_unlocked_cas_is_observable_but_does_not_satisfy_atomic_contract():
    e=golden();code=bytes.fromhex(e['bytes'])
    # Removing the prefix changes the backedge displacement by one byte.
    code=code.replace(bytes.fromhex('f0480fb10a'),bytes.fromhex('480fb10a')).replace(bytes.fromhex('74ea'),bytes.fromhex('74eb'))
    machine=prove(code,e['base'])
    assert not satisfies(machine['instruction'],{'rmw_operation':'fetch_and','width_bits':64},'target')


