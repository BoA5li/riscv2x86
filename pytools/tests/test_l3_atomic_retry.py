def native(tmp_path,width,operation,discard,reverse=False,optimization='-O0'):
    cc=shutil.which('gcc')
    if not cc:pytest.skip('native GCC unavailable')
    from riscv2x86_py.l3_atomic_deployment import build_side
    value=native_spec(width,operation,discard)
    if reverse:
        value['parameterTypes'].reverse();value.update(pointerParameter=1,valueParameter=0)
    builtin='__atomic_fetch_'+operation.removeprefix('fetch_')
    call=builtin+'(p,(uint'+str(width)+'_t)v,__ATOMIC_RELAXED)'
    body=call+';' if discard else 'return '+('(uint64_t)(int64_t)(int32_t)' if width==32 else '')+call+';'
    arguments=['uint'+str(width)+'_t *p','uint64_t v']
    if reverse:arguments.reverse()
    source=tmp_path/'different.c';source.write_text('#include <stdint.h>\n'+value['returnType']+' unrelated('+','.join(arguments)+'){'+body+'}\n')
    obj=tmp_path/'original.o';r=subprocess.run([cc,optimization,'-std=gnu11','-fno-lto','-fPIC','-c',source,'-o',obj],capture_output=True,text=True)
    assert r.returncode==0,r.stderr
    if optimization!='-O0':
        return function_mechanism(Elf(obj),'unrelated',value),value,None
    artifact=SimpleNamespace(artifact_path=str(obj),artifact_digest=digest(obj),artifact_id='target',build_identity=identity('build'))
    plan=samples(value)
    deployment=build_side(source,'target',plan,{'name':'unrelated'},{'targetCompiler':cc},artifact,tmp_path/'deployment',value)
    r=subprocess.run([deployment['executionArtifact']['artifactPath'],'a'*64],capture_output=True,text=True,check=True)
    rows=parse_samples(r.stdout,'a'*64,plan)
    for row in rows:
        assert int(row['after'][0],16)==result(operation,int(row['old'],16),int(row['input'],16),width)
        assert [int(v,16) for v in row['after'][1:]]==[0x31,0x72,0x53]
        old=int(row['old'],16)
        projected=(old-(1<<32) if width==32 and old&(1<<31) else old)&((1<<64)-1)
        assert int(row['result'],16)==(0 if discard else projected)
    assert Elf(obj).code('unrelated')==Elf(deployment['executionArtifact']['artifactPath']).code('unrelated')
    return deployment['machineMechanism'],value,rows


