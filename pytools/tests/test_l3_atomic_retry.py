@pytest.mark.parametrize('operation',tuple(OPERATIONS))
@pytest.mark.parametrize('width',(32,64))
def test_modular_operation_semantics_have_no_exchange_fallback(operation,width):
    mask=(1<<width)-1
    for old,value in ((0,0),(mask,0),(mask,mask),(1<<(width-1),mask),(7,3)):
        expected={'fetch_add':old+value,'exchange':value,'fetch_and':old&value,
                  'fetch_or':old|value,'fetch_xor':old^value}[operation]&mask
        assert result(operation,old,value,width)==expected
    with pytest.raises(ValueError):result('unrecognized',7,3,width)


