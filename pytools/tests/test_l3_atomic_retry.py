def trace_fixture(machine,count=2,object_base=0x2000):
    """Fixture PC/memory events only; no claimed emulator or concurrency run."""
    r=machine['retry'];pcs=r['prefixPCs']+r['loopPCs']*count;memory=[];timeline=[]
    roles={x['pc']:x for x in r['loopMemory']};init={x['pc'] for x in r['initialMemory']};attempt=0
    for step,pc in enumerate(pcs):
        if pc==r['casPC']:
            attempt+=1;kind='write' if attempt==count else 'read';address=object_base;width=machine['instruction']['width']//8
        elif pc in init:kind='read';address=object_base;width=machine['instruction']['width']//8
        elif pc in roles:kind='read';address=0x70000000+roles[pc]['stackOffset'];width=roles[pc]['widthBytes']
        else:continue
        timeline.append({'step':step,'memoryIndex':len(memory)})
        memory.append({'sample':0,'pc':pc,'address':address,'size':width,'access':kind})
    return {'paths':[{'pcs':pcs,'exit':machine['region']['end']}],'memory':memory,'memoryTimeline':timeline}


