"""Proof-bound access intervals in a direct execution unit.

Only equal compiler object identities establish aliasing here. Distinct object
identities do not establish disjointness: multi-object layouts need an additional
proved alias contract and are deliberately rejected by the current caller.
No observed memory values or semantic approval are generated by this graph.
"""
from .l3_trace_support import identity


def build(members,layout=None):
    objects={};accesses=[]
    for index,member in enumerate(members):
        access=member['spec']
        if access['access']=='none':continue
        oid=access['objectId'];shape={k:access[k] for k in ('size','alignment')}
        if oid in objects and objects[oid]!=shape:raise ValueError('L3_JOINT_OBJECT_GRAPH_SHAPE_CONFLICT')
        objects[oid]=shape
        offset,width=access['offset'],access['width']
        if (type(offset) is not int or type(width) is not int or width not in (1,2,4,8)
                or offset<0 or offset+width>shape['size'] or offset%width
                or shape['alignment']<width or access['access'] not in ('read','write')):
            raise ValueError('L3_JOINT_OBJECT_GRAPH_ACCESS_INVALID')
        accesses.append({'region':index,'fragmentId':member['fragmentId'],'objectId':oid,
            'start':offset,'end':offset+width,'access':access['access'],
            'sourceEffectId':access['sourceEffectId'],'authorityIdentity':member['authorityIdentity'],
            'relationIdentity':member['relationIdentity']})
    if layout is not None:
        from .object_layout_contract import materialize
        cases=[]
        for case in layout['layouts']:
            _,views=materialize(case,layout['views']);edges=[]
            for i,left in enumerate(accesses):
                for right in accesses[i+1:]:
                    a,b=views[left['objectId']],views[right['objectId']]
                    start=max(a['offset']+left['start'],b['offset']+right['start']);end=min(a['offset']+left['end'],b['offset']+right['end'])
                    if a['allocationId']==b['allocationId'] and start<end and 'write' in (left['access'],right['access']):
                        edges.append({'beforeRegion':left['region'],'afterRegion':right['region'],'allocationId':a['allocationId'],'overlap':[start,end],'relation':left['access']+'-before-'+right['access']})
            cases.append({'layoutIdentity':case['layoutIdentity'],'dependencies':edges})
        body={'schemaVersion':'riscv2x86.joint-object-access-graph.v2','objects':objects,'accesses':accesses,'layoutContractIdentity':layout['contractIdentity'],'layoutCases':cases,'semanticApproval':False,'valuesMeasured':False}
        return dict(body,graphIdentity=identity(body))
    if len(objects)!=1:raise ValueError('L3_JOINT_OBJECT_ALIAS_LAYOUT_REQUIRED')
    dependencies=[]
    for i,left in enumerate(accesses):
        for right in accesses[i+1:]:
            start,end=max(left['start'],right['start']),min(left['end'],right['end'])
            if start<end and 'write' in (left['access'],right['access']):
                dependencies.append({'beforeRegion':left['region'],'afterRegion':right['region'],
                    'objectId':left['objectId'],'overlap':[start,end],
                    'relation':left['access']+'-before-'+right['access']})
    body={'schemaVersion':'riscv2x86.joint-object-access-graph.v1','objects':objects,
        'accesses':accesses,'dependencies':dependencies,'aliasBasis':'same-compiler-object-identity',
        'semanticApproval':False,'valuesMeasured':False}
    return dict(body,graphIdentity=identity(body))
